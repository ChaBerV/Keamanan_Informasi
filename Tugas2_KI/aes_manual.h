static const unsigned char Rcon[11] = { 0x8d, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36 };

// Operasi Inti AES
void KeyExpansion(unsigned char* RoundKey, const unsigned char* Key) {
    for (int i = 0; i < 16; ++i) RoundKey[i] = Key[i];
    int bytesGenerated = 16;
    int rconIteration = 1;
    unsigned char tempa[4];
    while (bytesGenerated < 176) {
        for (int i = 0; i < 4; i++) tempa[i] = RoundKey[i + bytesGenerated - 4];
        if (bytesGenerated % 16 == 0) {
            unsigned char k = tempa[0];
            tempa[0] = sbox[tempa[1]] ^ Rcon[rconIteration++];
            tempa[1] = sbox[tempa[2]];
            tempa[2] = sbox[tempa[3]];
            tempa[3] = sbox[k];
        }
        for (unsigned char a = 0; a < 4; a++) {
            RoundKey[bytesGenerated] = RoundKey[bytesGenerated - 16] ^ tempa[a];
            bytesGenerated++;
        }
    }
}
void AddRoundKey(unsigned char* state, unsigned char* roundKey) {
    for (int i = 0; i < 16; ++i) state[i] ^= roundKey[i];
}
void SubBytes(unsigned char* state) {
    for (int i = 0; i < 16; ++i) state[i] = sbox[state[i]];
}
void InvSubBytes(unsigned char* state) {
    for (int i = 0; i < 16; ++i) state[i] = rsbox[state[i]];
}
void ShiftRows(unsigned char* state) {
    unsigned char temp;
    temp = state[1]; state[1] = state[5]; state[5] = state[9]; state[9] = state[13]; state[13] = temp;
    temp = state[2]; state[2] = state[10]; state[10] = temp;
    temp = state[6]; state[6] = state[14]; state[14] = temp;
    temp = state[15]; state[15] = state[11]; state[11] = state[7]; state[7] = state[3]; state[3] = temp;
}
void InvShiftRows(unsigned char* state) {
    unsigned char temp;
    temp = state[13]; state[13] = state[9]; state[9] = state[5]; state[5] = state[1]; state[1] = temp;
    temp = state[10]; state[10] = state[2]; state[2] = temp;
    temp = state[14]; state[14] = state[6]; state[6] = temp;
    temp = state[3]; state[3] = state[7]; state[7] = state[11]; state[11] = state[15]; state[15] = temp;
}
unsigned char gf_mul(unsigned char a, unsigned char b) {
    unsigned char p = 0;
    for (int i = 0; i < 8; i++) {
        if (b & 1) p ^= a;
        unsigned char hi_bit_set = (a & 0x80);
        a <<= 1;
        if (hi_bit_set) a ^= 0x1b;
        b >>= 1;
    }
    return p;
}
void MixColumns(unsigned char* state) {
    unsigned char Tmp, Tm, t;
    for (int i = 0; i < 16; i += 4) {
        t = state[i] ^ state[i + 1] ^ state[i + 2] ^ state[i + 3];
        Tmp = state[i];
        Tm = state[i] ^ state[i + 1]; Tm = gf_mul(Tm, 2); state[i] ^= Tm ^ t;
        Tm = state[i + 1] ^ state[i + 2]; Tm = gf_mul(Tm, 2); state[i + 1] ^= Tm ^ t;
        Tm = state[i + 2] ^ state[i + 3]; Tm = gf_mul(Tm, 2); state[i + 2] ^= Tm ^ t;
        Tm = state[i + 3] ^ Tmp; Tm = gf_mul(Tm, 2); state[i + 3] ^= Tm ^ t;
    }
}
void InvMixColumns(unsigned char* state) {
    for (int i = 0; i < 16; i += 4) {
        unsigned char a = state[i], b = state[i + 1], c = state[i + 2], d = state[i + 3];
        state[i] = gf_mul(a, 0x0e) ^ gf_mul(b, 0x0b) ^ gf_mul(c, 0x0d) ^ gf_mul(d, 0x09);
        state[i + 1] = gf_mul(a, 0x09) ^ gf_mul(b, 0x0e) ^ gf_mul(c, 0x0b) ^ gf_mul(d, 0x0d);
        state[i + 2] = gf_mul(a, 0x0d) ^ gf_mul(b, 0x09) ^ gf_mul(c, 0x0e) ^ gf_mul(d, 0x0b);
        state[i + 3] = gf_mul(a, 0x0b) ^ gf_mul(b, 0x0d) ^ gf_mul(c, 0x09) ^ gf_mul(d, 0x0e);
    }
}

// Proses 1 Blok (16 bytes)
void aes_encrypt_block(unsigned char* state, const unsigned char* Key) {
    unsigned char RoundKey[176];
    KeyExpansion(RoundKey, Key);
    AddRoundKey(state, RoundKey);
    for (int round = 1; round < 10; round++) {
        SubBytes(state); ShiftRows(state); MixColumns(state); AddRoundKey(state, RoundKey + round * 16);
    }
    SubBytes(state); ShiftRows(state); AddRoundKey(state, RoundKey + 160);
}
void aes_decrypt_block(unsigned char* state, const unsigned char* Key) {
    unsigned char RoundKey[176];
    KeyExpansion(RoundKey, Key);
    AddRoundKey(state, RoundKey + 160);
    for (int round = 9; round > 0; round--) {
        InvShiftRows(state); InvSubBytes(state); AddRoundKey(state, RoundKey + round * 16); InvMixColumns(state);
    }
    InvShiftRows(state); InvSubBytes(state); AddRoundKey(state, RoundKey);
}

// Helper: Hex String ↔ ASCII
string string_to_hex(const string& input) {
    stringstream ss;
    for (unsigned char c : input) ss << hex << setw(2) << setfill('0') << (int)c;
    return ss.str();
}
string hex_to_string(const string& hex_input) {
    string output = "";
    for (size_t i = 0; i < hex_input.length(); i += 2) {
        output += (char)strtol(hex_input.substr(i, 2).c_str(), nullptr, 16);
    }
    return output;
}
// Helper: Memastikan Kunci 16 Bytes
string pad_key(string key) {
    if (key.length() > 16) return key.substr(0, 16);
    return key.append(16 - key.length(), '*');
}

// Wrappers: Encrypt & Decrypt String Full (Mode ECB dengan PKCS#7)
string AES_Encrypt(string plaintext, string key) {
    key = pad_key(key);
    int pad_len = 16 - (plaintext.length() % 16);
    plaintext.append(pad_len, (char)pad_len); // PKCS#7
    string ciphertext = "";
    for (size_t i = 0; i < plaintext.length(); i += 16) {
        unsigned char block[16];
        memcpy(block, plaintext.substr(i, 16).c_str(), 16);
        aes_encrypt_block(block, (const unsigned char*)key.c_str());
        ciphertext.append((char*)block, 16);
    }
    return string_to_hex(ciphertext); // Output format Wajib HEX
}

string AES_Decrypt(string hex_ciphertext, string key) {
    key = pad_key(key);
    string raw_cipher = hex_to_string(hex_ciphertext);
    string plaintext = "";
    for (size_t i = 0; i < raw_cipher.length(); i += 16) {
        unsigned char block[16];
        memcpy(block, raw_cipher.substr(i, 16).c_str(), 16);
        aes_decrypt_block(block, (const unsigned char*)key.c_str());
        plaintext.append((char*)block, 16);
    }
    if(plaintext.empty()) return "";
    int pad_len = plaintext.back();
    if (pad_len > 0 && pad_len <= 16) plaintext.erase(plaintext.length() - pad_len);
    return plaintext;
}
